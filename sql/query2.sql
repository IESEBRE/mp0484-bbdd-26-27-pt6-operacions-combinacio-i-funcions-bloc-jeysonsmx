SELECT FIRST_NAME, 'comença per vocal' AS TIPUS
FROM EMPLOYEES
WHERE UPPER(SUBSTR(FIRST_NAME, 1, 1)) IN ('A', 'E', 'I', 'O', 'U')
UNION
SELECT FIRST_NAME, 'comença per consonant' AS TIPUS
FROM EMPLOYEES
WHERE UPPER(SUBSTR(FIRST_NAME, 1, 1)) NOT IN ('A', 'E', 'I', 'O', 'U')
ORDER BY TIPUS ASC, FIRST_NAME DESC;
